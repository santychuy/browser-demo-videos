const providers = [
  ["groq", "GROQ_API_KEY", "troy"],
  ["openai", "OPENAI_API_KEY", "marin"],
  ["openai-live", "OPENAI_API_KEY", "marin"],
  ["xai", "XAI_API_KEY", "eve"],
];
const restProviders = providers.filter(
  ([provider]) => provider !== "openai-live",
);
const keyNames = [...new Set(providers.map(([, name]) => name))];
const script = "Review the two projects, then export.";

function story(provider, voice) {
  return {
    version: 1,
    title: "Narration boundary",
    url: "http://127.0.0.1:4173/",
    narration: { provider, ...(voice ? { voice } : {}) },
    scenes: [{ id: "overview", text: "Review projects.", narration: script }],
  };
}

// A tiny independent PCM WAV fixture, not bytes generated by the adapter.
function wav() {
  const audio = Buffer.alloc(48);
  audio.write("RIFF", 0);
  audio.writeUInt32LE(40, 4);
  audio.write("WAVEfmt ", 8);
  audio.writeUInt32LE(16, 16);
  audio.writeUInt16LE(1, 20);
  audio.writeUInt16LE(1, 22);
  audio.writeUInt32LE(48000, 24);
  audio.writeUInt32LE(96000, 28);
  audio.writeUInt16LE(2, 32);
  audio.writeUInt16LE(16, 34);
  audio.write("data", 36);
  audio.writeUInt32LE(4, 40);
  audio.writeInt16LE(42, 44);
  audio.writeInt16LE(-42, 46);
  return audio;
}

function openaiReply({
  transcript = script,
  data = wav().toString("base64"),
  finish = "stop",
  refusal,
} = {}) {
  return {
    choices: [
      {
        finish_reason: finish,
        message: {
          audio: { data, transcript },
          ...(refusal ? { refusal } : {}),
        },
      },
    ],
  };
}

async function isolated(t, { tools = false } = {}) {
  const names = ["PATH", "PATHEXT", "BROWSER_DEMO_HOME", ...keyNames];
  const previous = names.map((name) => [name, process.env[name]]);
  for (const [name] of previous) delete process.env[name];
  const directory = await mkdtemp(join(tmpdir(), "browser-demo-narration-"));
  process.env.PATH = tools ? directory : "";
  process.env.PATHEXT = "";
  process.env.BROWSER_DEMO_HOME = directory;
  if (tools) {
    // Discovery-only sentinels. Successful synthesis/probing is not mocked or
    // claimed here, and no test executes these files or requires macOS speech.
    await writeFile(join(directory, "say"), "not an executable program", {
      mode: 0o700,
    });
    await writeFile(join(directory, "ffprobe"), "not an executable program", {
      mode: 0o700,
    });
  }
  t.after(async () => {
    for (const [name, value] of previous) {
      if (value === undefined) delete process.env[name];
      else process.env[name] = value;
    }
    await rm(directory, { recursive: true, force: true });
  });
  const fetchMock = t.mock.method(globalThis, "fetch", async () => {
    throw new Error(
      "Unexpected network request: tests never use real providers",
    );
  });
  return { directory, fetchMock };
}

function cloudRequest(provider, voice) {
  return { provider, voice, text: script, allowCloud: true };
}

test("missing selected keys resolve only to Samantha, never another configured cloud", async (t) => {
  const { fetchMock } = await isolated(t, { tools: true });
  for (const [provider, keyEnv, voice] of providers) {
    for (const name of keyNames) process.env[name] = "unrelated-configured-key";
    process.env[keyEnv] = " \t ";
    assert.deepEqual(resolveNarration(story(provider, voice)), {
      requestedProvider: provider,
      requestedVoice: voice,
      provider: "system",
      voice: "Samantha",
      fallbackReason: "missing-api-key",
    });
    await assert.rejects(
      requestSpeech(cloudRequest(provider, voice)),
      new RegExp(keyEnv),
    );
  }
  assert.deepEqual(resolveNarration(story("system", "Alex")), {
    requestedProvider: "system",
    requestedVoice: "Alex",
    provider: "system",
    voice: "Alex",
  });
  assert.equal(fetchMock.mock.callCount(), 0);
});

