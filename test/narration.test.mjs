test("OpenAI sends documented chat audio JSON and accepts only a matching WAV transcript", async (t) => {
  const { fetchMock } = await isolated(t);
  process.env.OPENAI_API_KEY = "openai-test-key";
  fetchMock.mock.mockImplementation(async () =>
    Response.json(
      openaiReply({
        transcript: "ＲＥＶＩＥＷ the two projects — then export!",
      }),
    ),
  );
  const result = await requestSpeech(cloudRequest("openai", "marin"));
  assert.deepEqual(result.audio, wav());
  assert.equal(
    result.transcript,
    "ＲＥＶＩＥＷ the two projects — then export!",
  );
  const [url, options] = fetchMock.mock.calls[0].arguments;
  assert.equal(url, "https://api.openai.com/v1/chat/completions");
  assert.equal(options.method, "POST");
  assert.equal(options.redirect, "error");
  assert.equal(options.headers.Authorization, "Bearer openai-test-key");
  assert.equal(options.headers["Content-Type"], "application/json");
  assert.ok(options.signal instanceof AbortSignal);
  assert.equal(options.signal.aborted, false);
  const body = JSON.parse(options.body);
  assert.equal(body.model, "gpt-audio-1.5");
  assert.equal(body.store, false);
  assert.deepEqual(body.modalities, ["text", "audio"]);
  assert.deepEqual(body.audio, { voice: "marin", format: "wav" });
  assert.deepEqual(body.messages[1], { role: "user", content: script });
  assert.equal(body.messages.length, 2);
  assert.equal(body.messages[0].role, "system");
  assert.equal(fetchMock.mock.callCount(), 1);
});

