test("configured resolution reports the effective cloud and fixed model without credential data", async (t) => {
  const { directory } = await isolated(t);
  // Resolver discovery only: any attempt to connect with this fixture must fail.
  const wsDirectory = join(directory, "live-runtime", "node_modules", "ws");
  await mkdir(wsDirectory, { recursive: true });
  await writeFile(
    join(wsDirectory, "package.json"),
    JSON.stringify({ name: "ws", version: "8.22.0", main: "index.cjs" }),
  );
  await writeFile(
    join(wsDirectory, "index.cjs"),
    'module.exports = function () { throw new Error("Discovery fixture cannot connect"); };',
  );
  const expectedModels = {
    groq: "canopylabs/orpheus-v1-english",
    openai: "gpt-audio-1.5",
    "openai-live": "gpt-live-1",
  };
  for (const [provider, keyEnv, voice] of providers) {
    process.env[keyEnv] = "test-key-do-not-publish";
    const resolved = resolveNarration(story(provider, voice), {
      allowCloud: true,
    });
    assert.deepEqual(resolved, {
      requestedProvider: provider,
      requestedVoice: voice,
      provider,
      voice,
      ...(expectedModels[provider] ? { model: expectedModels[provider] } : {}),
    });
    assert.equal(
      JSON.stringify(resolved).includes("test-key-do-not-publish"),
      false,
    );
  }
});

