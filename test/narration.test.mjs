test("OpenAI refuses rewritten, truncated, refused and malformed speech instead of saving audio", async (t) => {
  const { directory, fetchMock } = await isolated(t, { tools: true });
  process.env.OPENAI_API_KEY = "openai-test-secret";
  const cases = [
    [
      "added words",
      openaiReply({ transcript: `${script} Thanks.` }),
      /transcript does not match/,
    ],
    [
      "missing words",
      openaiReply({ transcript: "Review the two projects." }),
      /transcript does not match/,
    ],
    [
      "reordered words",
      openaiReply({ transcript: "Export then review the two projects." }),
      /transcript does not match/,
    ],
    [
      "changed number",
      openaiReply({ transcript: "Review the three projects, then export." }),
      /transcript does not match/,
    ],
    [
      "numeral spelling",
      openaiReply({ transcript: "Review the 2 projects, then export." }),
      /transcript does not match/,
    ],
    ["truncated", openaiReply({ finish: "length" }), /incomplete speech/],
    [
      "filtered",
      openaiReply({ finish: "content_filter" }),
      /incomplete speech/,
    ],
    ["refused", openaiReply({ refusal: "provider-secret-body" }), /refused/],
    [
      "no transcript",
      {
        choices: [
          {
            finish_reason: "stop",
            message: { audio: { data: wav().toString("base64") } },
          },
        ],
      },
      /malformed/,
    ],
    ["no choice", { choices: [] }, /incomplete speech/],
    ["invalid base64", openaiReply({ data: "not!base64" }), /malformed/],
    [
      "noncanonical base64",
      openaiReply({
        data:
          Buffer.concat([wav(), Buffer.from([0])])
            .toString("base64")
            .slice(0, -4) + "AB==",
      }),
      /malformed base64/,
    ],
    ["empty audio", openaiReply({ data: "" }), /malformed/],
    [
      "non-WAV",
      openaiReply({
        data: Buffer.from("This is not a WAV file").toString("base64"),
      }),
      /malformed WAV/,
    ],
  ];
  for (const [index, [name, payload, expected]] of cases.entries()) {
    fetchMock.mock.mockImplementation(async () => Response.json(payload));
    const clipDirectory = join(directory, `case-${index}`);
    await assert.rejects(
      prepareNarration(story("openai"), {
        directory: clipDirectory,
        allowCloud: true,
      }),
      (error) => {
        assert.match(error.message, expected, name);
        assert.equal(error.message.includes("provider-secret-body"), false);
        assert.equal(error.message.includes("openai-test-secret"), false);
        return true;
      },
    );
    assert.deepEqual(await readdir(clipDirectory), ["01-overview.txt"], name);
  }
  fetchMock.mock.mockImplementation(async () => new Response('{"choices":['));
  await assert.rejects(
    requestSpeech(cloudRequest("openai", "marin")),
    /malformed JSON/,
  );
  assert.equal(fetchMock.mock.callCount(), cases.length + 1);
});

test("provider HTTP failures never use local fallback, retry, consume error bodies or leak secrets", async (t) => {
  const { directory, fetchMock } = await isolated(t, { tools: true });
  let calls = 0;
  for (const [provider, keyEnv] of restProviders) {
    process.env[keyEnv] = "private-configured-key";
    for (const status of [401, 403, 429, 500]) {
      let cancelled = false;
      fetchMock.mock.mockImplementation(async () => {
        // Deliberately no provider body access is possible without a failing getter.
        return {
          ok: false,
          status,
          body: {
            async cancel() {
              cancelled = true;
            },
          },
          get text() {
            throw new Error("private-provider-body");
          },
          get json() {
            throw new Error("private-provider-body");
          },
        };
      });
      const clipDirectory = join(directory, `${provider}-${status}`);
      await assert.rejects(
        prepareNarration(story(provider), {
          directory: clipDirectory,
          allowCloud: true,
        }),
        (error) => {
          assert.match(error.message, new RegExp(`HTTP ${status}`));
          assert.match(error.message, /no fallback was used/);
          assert.doesNotMatch(error.message, /private-/);
          return true;
        },
      );
      assert.equal(cancelled, true);
      assert.deepEqual(await readdir(clipDirectory), ["01-overview.txt"]);
      assert.equal(fetchMock.mock.callCount(), ++calls);
    }
  }
});

test("network and stream failures are sanitized and never trigger a provider retry or fallback", async (t) => {
  const { fetchMock } = await isolated(t);
  let calls = 0;
  for (const [provider, keyEnv, voice] of restProviders) {
    process.env[keyEnv] = "private-secret-key";
    fetchMock.mock.mockImplementation(async () => {
      throw new Error("private-secret-key private-network-details");
    });
    await assert.rejects(
      requestSpeech(cloudRequest(provider, voice)),
      (error) => {
        assert.match(error.message, /request failed/);
        assert.match(error.message, /no fallback was used/);
        assert.doesNotMatch(error.message, /private-/);
        return true;
      },
    );
    assert.equal(fetchMock.mock.callCount(), ++calls);
    fetchMock.mock.mockImplementation(
      async () =>
        new Response(
          new ReadableStream({
            start(controller) {
              controller.error(new Error("private-secret-key stream failure"));
            },
          }),
        ),
    );
    await assert.rejects(
      requestSpeech(cloudRequest(provider, voice)),
      (error) => {
        assert.match(error.message, /could not be read/);
        assert.doesNotMatch(error.message, /private-/);
        return true;
      },
    );
    assert.equal(fetchMock.mock.callCount(), ++calls);
  }
});

test("bounded responses reject oversized envelopes before reading and reject non-WAV raw output", async (t) => {
  const { fetchMock } = await isolated(t);
  for (const [provider, keyEnv, voice] of restProviders) {
    process.env[keyEnv] = "fake-key";
    fetchMock.mock.mockImplementation(
      async () =>
        new Response("private-provider-data", {
          headers: { "content-length": "100000000" },
        }),
    );
    await assert.rejects(
      requestSpeech(cloudRequest(provider, voice)),
      /safety byte limit/,
    );
  }
  // Do not trust Content-Length: a chunked response must obey the same bound.
  // Reuse one chunk so this tests the byte limit without a huge fixture.
  const chunk = new Uint8Array(1024 * 1024);
  for (const [provider, voice] of [
    ["openai", "marin"],
    ["xai", "eve"],
  ]) {
    let cancelled = false;
    fetchMock.mock.mockImplementation(async () => {
      let sent = 0;
      return new Response(
        new ReadableStream({
          pull(controller) {
            if (sent++ < 100) controller.enqueue(chunk);
            else controller.close();
          },
          cancel() {
            cancelled = true;
          },
        }),
      );
    });
    await assert.rejects(
      requestSpeech(cloudRequest(provider, voice)),
      /safety byte limit/,
    );
    assert.equal(cancelled, true);
  }
  for (const provider of ["groq", "xai"]) {
    fetchMock.mock.mockImplementation(async () =>
      Response.json({ audio: "not raw WAV" }),
    );
    await assert.rejects(
      requestSpeech(
        cloudRequest(provider, provider === "groq" ? "troy" : "eve"),
      ),
      /malformed WAV/,
    );
  }
});
